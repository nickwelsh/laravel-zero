<?php

declare(strict_types=1);

namespace LaravelZero\Generation;

use LaravelZero\Metadata\ModelRegistry;

final class TypeScriptGenerator
{
    public function generateReact(string $contracts, string $options): string
    {
        return "// Generated by Laravel Zero. Edit connection options in the imported config module.\n"
            ."import {createZeroProvider} from '@laravel-zero/client/react';\n"
            .'import {schema, mutators} from '.$this->json($contracts).";\n"
            .'import {options} from '.$this->json($options).";\n"
            ."export const ZeroProvider = createZeroProvider(schema, mutators, options);\n";
    }

    public function generate(ModelRegistry $registry): string
    {
        $models = $registry->all();
        ksort($models);
        $tables = [];
        foreach ($models as $model) {
            $tables[$model->table] = ['columns' => $model->columns, 'key' => [$model->key]];
        }

        foreach ($registry->pivotColumns() as $table => $columns) {
            $tables[$table] = ['columns' => $columns, 'key' => $registry->pivotKeys()[$table]];
        }

        ksort($tables);
        $names = [];
        foreach (array_keys($tables) as $i => $table) {
            $names[$table] = 'table'.$i;
        }

        $lines = [
            '// Generated by Laravel Zero. Run php artisan zero:generate after model changes.',
            "import {table, string, number, boolean, json, relationships, createSchema} from '@rocicorp/zero';",
            "import {createLaravelZero, type ContractMap, type ModelRow, type ModelInstance} from '@laravel-zero/client';", '',
        ];
        foreach ($tables as $name => $table) {
            $lines[] = 'const '.$names[$name].' = table('.$this->json($name).').columns({';
            foreach ($table['columns'] as $field => $column) {
                $lines[] = '  '.$this->json($field).': '.$column['type'].'()'.($column['nullable'] ? '.optional()' : '').',';
            }

            $lines[] = '} ).primaryKey('.implode(', ', array_map($this->json(...), $table['key'])).');';
        }

        $relations = [];
        foreach ($models as $model) {
            if ($model->relations === []) {
                continue;
            }

            $variable = $names[$model->table].'Relations';
            $relations[] = $variable;
            $lines[] = 'const '.$variable.' = relationships('.$names[$model->table].', ({one, many}) => ({';
            foreach ($model->relations as $name => $relation) {
                $connections = [];
                foreach ($relation['path'] as $hop) {
                    $connections[] = '{sourceField: '.$this->json($hop['source']).', destField: '.$this->json($hop['dest']).', destSchema: '.$names[$hop['table']].'}';
                }

                $lines[] = '  '.$this->json($name).': '.$relation['cardinality'].'('.implode(', ', $connections).'),';
            }

            $lines[] = '}));';
        }

        $lines[] = 'export const schema = createSchema({tables: ['.implode(', ', $names).'], relationships: ['.implode(', ', $relations).'], enableLegacyQueries: false, enableLegacyMutators: false});';
        $definitions = array_map(fn (\LaravelZero\Metadata\ModelMetadata $model): array => $model->toArray(), $models);
        $lines[] = 'export const definitions = '.$this->json((object) $definitions, true).' as const satisfies ContractMap;';
        $lines[] = 'export const {models, queries, mutators} = createLaravelZero(schema, definitions);';
        foreach ($models as $model) {
            $lines[] = 'export const '.$model->name.' = models.'.$model->name.';';
            $lines[] = 'export type '.$model->name.' = ModelInstance<typeof schema, typeof definitions, '.$this->json($model->name).'>;';
            $lines[] = 'export type '.$model->name.'Row = ModelRow<typeof definitions, '.$this->json($model->name).'>;';
        }

        return implode("\n", $lines)."\n";
    }

    private function json(mixed $value, bool $pretty = false): string
    {
        return json_encode($value, JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES | ($pretty ? JSON_PRETTY_PRINT : 0));
    }
}
